-- Messages Postgres refused to store (a data error). The poller keeps moving, so the message is kept
-- here with the error and its sanitised payload for a person to look at, instead of being lost.
CREATE TABLE inbound_failures (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  graph_id TEXT NOT NULL UNIQUE,
  internet_message_id TEXT,
  error TEXT NOT NULL,
  payload JSONB NOT NULL,
  created_at TEXT NOT NULL,
  resolved_at TEXT
);
