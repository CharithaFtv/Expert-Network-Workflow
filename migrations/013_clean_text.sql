-- Step 3d: the cleaned text of a verified message, and the links found in it.
--
-- text_clean   the new content only (HTML converted to text, quoted history and signature set aside)
-- text_removed what was set aside, labelled, so nothing is lost and a person can check the cut
-- clean_info   what the cleaner did (markers used, hidden text removed, limits hit) as JSON
-- clean_version  which version of the rules produced it, so messages can be re-cleaned when the rules improve
-- The original body stays untouched in `body`.
ALTER TABLE inbound_messages
  ADD COLUMN text_clean TEXT,
  ADD COLUMN text_removed TEXT,
  ADD COLUMN clean_info JSONB,
  ADD COLUMN cleaned_at TEXT,
  ADD COLUMN clean_version INTEGER,
  ADD COLUMN clean_attempts INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN clean_error TEXT;

-- Links found in the new content of a verified message. They are stored as data and are never opened by
-- this code. A link can carry a secret token in its address, so it is kept out of logs and is removed with
-- the message when its retention date passes.
CREATE TABLE inbound_links (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id INTEGER NOT NULL REFERENCES inbound_messages(id) ON DELETE CASCADE,
  url TEXT NOT NULL,
  host TEXT NOT NULL,
  link_text TEXT NOT NULL DEFAULT '',
  source TEXT NOT NULL CHECK (source IN ('html', 'text')),
  -- the visible text names a different site than the link goes to
  text_mismatch BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TEXT NOT NULL,
  UNIQUE (message_id, url)
);
CREATE INDEX idx_inbound_links_message ON inbound_links(message_id);
