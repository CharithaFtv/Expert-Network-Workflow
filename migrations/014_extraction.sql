-- Step 3e: what the language model made of a verified message.
--
-- extractions            one row per message that has been through the model (or was passed over)
-- extracted_candidates   the experts found in it, each field with its confidence and a quote from the email
--
-- Nothing here is a fact. Every candidate starts as 'Pending review' and only a person's confirmation (step 3f)
-- makes it real. A message the model could not handle is marked 'Needs manual entry' and the workflow goes on.
CREATE TABLE extractions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id INTEGER NOT NULL UNIQUE REFERENCES inbound_messages(id) ON DELETE CASCADE,
  status TEXT NOT NULL CHECK (status IN ('Extracted', 'Classified', 'Needs manual entry', 'Skipped')),
  category TEXT,
  confidence REAL,
  reason TEXT,
  model TEXT,
  prompt_version TEXT,
  input_chars INTEGER,
  truncated BOOLEAN NOT NULL DEFAULT FALSE,
  error TEXT,
  -- Which calls were made, how many tries, request IDs, token counts, and which fields were dropped and why.
  -- It holds no email text.
  audit JSONB,
  -- The model's parsed answers. They contain personal data from the email, so they are removed with the message.
  raw JSONB,
  created_at TEXT NOT NULL
);

CREATE TABLE extracted_candidates (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  extraction_id INTEGER NOT NULL REFERENCES extractions(id) ON DELETE CASCADE,
  message_id INTEGER NOT NULL REFERENCES inbound_messages(id) ON DELETE CASCADE,
  project_id INTEGER NOT NULL REFERENCES projects(id),
  vendor_id INTEGER REFERENCES vendors(id),
  position INTEGER NOT NULL,
  -- The validated fields, each as {value, confidence, quote}.
  data JSONB NOT NULL,
  name_norm TEXT NOT NULL,
  employer_norm TEXT NOT NULL DEFAULT '',
  -- Is this someone already proposed by this vendor on this project? Never merged automatically.
  match_status TEXT NOT NULL CHECK (match_status IN ('New', 'Suggested update', 'Ambiguous')),
  matches INTEGER[] NOT NULL DEFAULT '{}',
  review_status TEXT NOT NULL DEFAULT 'Pending review' CHECK (review_status IN ('Pending review', 'Confirmed', 'Rejected')),
  created_at TEXT NOT NULL
);
CREATE INDEX idx_candidates_project ON extracted_candidates(project_id, vendor_id, review_status);
CREATE INDEX idx_candidates_message ON extracted_candidates(message_id);

-- A message the model could not be reached for is tried again on a later poll, a few times, then marked.
ALTER TABLE inbound_messages
  ADD COLUMN extraction_attempts INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN extraction_error TEXT;
