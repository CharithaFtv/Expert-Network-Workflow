-- Step 3c: attachments (kept small and only for verified mail) and a retention hook.
--
-- Attachments are downloaded only for Matched messages (known vendor, known project). Anything that
-- is not safe or small enough is recorded as Skipped with the reason, so nothing disappears silently.
-- Nothing is ever opened or run here.
CREATE TABLE inbound_attachments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id INTEGER NOT NULL REFERENCES inbound_messages(id) ON DELETE CASCADE,
  graph_attachment_id TEXT NOT NULL,
  name TEXT NOT NULL,
  content_type TEXT,
  size_bytes INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL CHECK (status IN ('Stored', 'Skipped', 'Purged')),
  skip_reason TEXT,
  sha256 TEXT,
  content BYTEA,
  created_at TEXT NOT NULL,
  UNIQUE (message_id, graph_attachment_id)
);

-- When set, the message body, headers and attachment bytes are purged after this time (see purgeExpired).
-- Nothing sets it yet: the retention period is for FTV compliance to decide, so nothing expires today.
-- attachments_fetched_at: the attachment step finished for this message (so it is not repeated).
ALTER TABLE inbound_messages
  ADD COLUMN retain_until TEXT,
  ADD COLUMN purged_at TEXT,
  ADD COLUMN attachments_fetched_at TEXT;
