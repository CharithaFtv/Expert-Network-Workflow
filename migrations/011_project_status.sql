-- Project states: Just opened -> Ongoing -> Compliance -> Closed (see src/lib/projectStatus.ts for the allowed moves).
-- Closing a project starts the retention clock for its received mail (see closeProject / purge-inbox).
ALTER TABLE projects ALTER COLUMN status SET DEFAULT 'Just opened';
UPDATE projects SET status = 'Just opened' WHERE status = 'Submitted';
ALTER TABLE projects
  ADD COLUMN closed_at TEXT,
  ADD CONSTRAINT projects_status_check CHECK (status IN ('Just opened', 'Ongoing', 'Compliance', 'Closed'));

-- Who moved a project from which state to which, and when (also feeds the project timeline in 3g).
CREATE TABLE project_status_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id),
  from_status TEXT NOT NULL,
  to_status TEXT NOT NULL,
  user_id TEXT NOT NULL,
  user_name TEXT NOT NULL,
  changed_at TEXT NOT NULL
);
CREATE INDEX idx_status_log_project ON project_status_log(project_id, id);
