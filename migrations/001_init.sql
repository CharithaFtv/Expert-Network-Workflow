-- Same tables as the SQLite build. Timestamps stay ISO-8601 TEXT so behaviour is unchanged;
-- convert to TIMESTAMPTZ in a later, separate migration.
CREATE TABLE vendors (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  intake_email TEXT,
  active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE projects (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT UNIQUE,
  title TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Submitted',
  deal_id TEXT NOT NULL,
  deal_name TEXT NOT NULL,
  deal_status TEXT NOT NULL,
  deal_stage TEXT,
  company_name TEXT,
  sector TEXT,
  requester_id TEXT NOT NULL,
  requester_name TEXT NOT NULL,
  brief TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE project_members (
  project_id INTEGER NOT NULL REFERENCES projects(id),
  user_id TEXT NOT NULL,
  user_name TEXT NOT NULL,
  user_email TEXT NOT NULL,
  role TEXT NOT NULL,
  PRIMARY KEY (project_id, user_id)
);

CREATE TABLE project_vendors (
  project_id INTEGER NOT NULL REFERENCES projects(id),
  vendor_id INTEGER NOT NULL REFERENCES vendors(id),
  status TEXT NOT NULL DEFAULT 'Pending send',
  PRIMARY KEY (project_id, vendor_id)
);

CREATE TABLE notifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL,
  project_id INTEGER REFERENCES projects(id),
  message TEXT NOT NULL,
  read_at TEXT,
  created_at TEXT NOT NULL
);
CREATE INDEX idx_notifications_user ON notifications(user_id, read_at);

CREATE TABLE outbox (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER REFERENCES projects(id),
  kind TEXT NOT NULL,
  recipient TEXT NOT NULL,
  subject TEXT NOT NULL,
  body TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Queued',
  created_at TEXT NOT NULL
);
