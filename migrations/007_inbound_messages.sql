-- Step 3a: mail received in the shared mailbox. Timestamps stay ISO-8601 TEXT like the other tables.
-- graph_id is Graph's immutable message ID (stable if the message is moved between folders).
-- internet_message_id is the RFC 5322 Message-ID: the same email re-delivered gets a new graph_id
-- but the same Message-ID, so both are unique and either one drops a duplicate.
CREATE TABLE inbound_messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  graph_id TEXT NOT NULL UNIQUE,
  internet_message_id TEXT UNIQUE,
  conversation_id TEXT,
  received_at TEXT NOT NULL,
  from_address TEXT,
  from_name TEXT,
  to_addresses TEXT[] NOT NULL DEFAULT '{}',
  subject TEXT NOT NULL DEFAULT '',
  body_type TEXT NOT NULL DEFAULT 'text',
  body TEXT NOT NULL DEFAULT '',
  has_attachments BOOLEAN NOT NULL DEFAULT FALSE,
  headers JSONB,
  status TEXT NOT NULL DEFAULT 'Received',
  created_at TEXT NOT NULL
);
CREATE INDEX idx_inbound_conversation ON inbound_messages(conversation_id);
CREATE INDEX idx_inbound_status ON inbound_messages(status);

-- One row per mailbox folder we follow: the Graph delta link is the cursor.
CREATE TABLE mailbox_sync (
  name TEXT PRIMARY KEY,
  delta_link TEXT,
  since TEXT,
  updated_at TEXT NOT NULL
);
